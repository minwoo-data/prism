#!/usr/bin/env node
/*
 * Deterministic evidence checker for prism v0.2 (the keystone rung).
 *
 * The Evidence pass claims a finding is SUPPORTED by citing `file:line — quote`.
 * An LLM can fabricate a plausible-looking citation that satisfies the schema.
 * This script makes the central claim machine-checkable the same way
 * parse-findings.js made discovery parsing deterministic: for each finding it
 * confirms the file exists, the line range is valid, and the quoted text
 * actually appears at (or very near) the cited lines. A finding that fails is
 * auto-downgraded so a hallucinated quote can never ship as SUPPORTED.
 *
 * It ALSO computes the fingerprint in code (LLMs cannot compute sha1), so
 * cross-run dedup is stable instead of freehand hex that changes every run.
 *
 * Input  (stdin or file): a JSON array of finding records v2 (see prism SKILL.md).
 * Output (stdout): the same array, each record annotated with:
 *   - fingerprint          : recomputed deterministically (overwrites model value)
 *   - status               : downgraded to SUSPECTED if a SUPPORTED/REPRODUCED
 *                            claim's quote does not verify
 *   - confidence.evidence_strength : clamped to what actually verified
 *   - _evidence_check      : {checked, quote_found, matched_lines, note}
 *
 * Downgrade contract (never silently keep a bogus SUPPORTED):
 *   SUPPORTED/REPRODUCED + file missing        -> SUSPECTED  (missing: FILE_NOT_FOUND)
 *   SUPPORTED/REPRODUCED + lines out of range  -> SUSPECTED  (missing: LINES_OUT_OF_RANGE)
 *   SUPPORTED/REPRODUCED + quote not found      -> SUSPECTED  (missing: EVIDENCE_QUOTE_MISMATCH)
 *   REPRODUCED is only trusted when reproduction.status === 'REPRODUCED' AND the
 *     static quote also verifies; otherwise it falls back to the SUPPORTED rules.
 *
 * Never throws, never mutates source files, no deps. Windows/POSIX safe.
 *
 * Usage:
 *   node verify-evidence.js findings.json <repo-root> > checked.json
 *   node verify-evidence.js --selftest
 *
 * SINGLE-SOURCED: canonical = prism-all/verify-evidence.js; prism-codex + prism
 * copies are generated by skills/sync-review-parsers.sh. Edit ONLY the canonical.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const GROUNDED = new Set(['SUPPORTED', 'REPRODUCED']);
const CTX = 2;                 // allow the quote to sit within +/-CTX of the cited lines
const NL = /\r\n|\n|\r/;

// Normalize a path for hashing: repo-relative, forward slashes, no leading ./,
// lowercased ONLY on Windows-style drive-letter inputs (case-insensitive FS).
function normPathForHash(file, repoRoot) {
  if (!file) return '<none>';
  let f = String(file).replace(/\\/g, '/');
  if (repoRoot) {
    const r = String(repoRoot).replace(/\\/g, '/').replace(/\/+$/, '');
    if (f.startsWith(r + '/')) f = f.slice(r.length + 1);
  }
  f = f.replace(/^\.\//, '');
  if (/^[a-zA-Z]:\//.test(f)) f = f.toLowerCase();   // drive letter => case-insensitive
  return f;
}

// A short, stable slug of the claim so two distinct defects in the same
// symbol+category do NOT collide (the review's A3-1 collision case).
function claimStem(claim) {
  const s = String(claim == null ? '' : claim)
    .toLowerCase()
    .replace(/[`'"]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
    .slice(0, 8)
    .join('-');
  return s || '<none>';
}

function computeFingerprint(rec, repoRoot) {
  const file = normPathForHash(rec.file, repoRoot);
  const symbol = rec.symbol ? String(rec.symbol) : '<none>';
  const category = rec.category ? String(rec.category) : '<none>';
  const stem = claimStem(rec.claim);
  const basis = `${file}|${symbol}|${category}|${stem}`;
  return {
    fingerprint: crypto.createHash('sha1').update(basis).digest('hex').slice(0, 12),
    unpinned: !rec.file,   // file:null findings are excluded from CI dedup
  };
}

// Parse "lines" which may be "84-102", "98", 98, or [84,102].
function parseLines(lines) {
  if (lines == null) return null;
  if (Array.isArray(lines)) {
    const a = Number(lines[0]), b = Number(lines[lines.length - 1]);
    return Number.isFinite(a) ? [a, Number.isFinite(b) ? b : a] : null;
  }
  const m = String(lines).match(/(\d+)\s*(?:-\s*(\d+))?/);
  if (!m) return null;
  const a = Number(m[1]), b = m[2] ? Number(m[2]) : a;
  return [Math.min(a, b), Math.max(a, b)];
}

// Pull the quoted substring out of an evidence entry like
// `src/auth.py:98 — token record remains active after update`.
function quoteFromEvidence(ev) {
  const s = String(ev == null ? '' : ev);
  // Prefer text after an em/en dash or ' - ' separator; else the whole string.
  const m = s.match(/[—–]\s*(.+)$/) || s.match(/\s-\s+(.+)$/);
  return (m ? m[1] : s).trim();
}

// Loose containment: collapse whitespace, case-insensitive, so trivial
// reflow/indent differences don't cause false mismatches while a fabricated
// quote (absent from the file) still fails.
function loose(s) {
  return String(s).replace(/\s+/g, ' ').trim().toLowerCase();
}

function checkOne(rec, repoRoot) {
  const out = Object.assign({}, rec);
  out.confidence = Object.assign({}, rec.confidence);
  const fp = computeFingerprint(rec, repoRoot);
  out.fingerprint = fp.fingerprint;
  if (fp.unpinned) out.unpinned = true;

  if (!GROUNDED.has(rec.status)) {
    out._evidence_check = { checked: false, note: 'status not grounded — no quote check' };
    return out;
  }

  const downgrade = (missing) => {
    out.status = 'SUSPECTED';
    out.missing = missing;
    out.confidence.evidence_strength = 'NONE';
    out.confidence.label = 'LOW';
    out._evidence_check = { checked: true, quote_found: false, note: missing };
    return out;
  };

  if (!rec.file) return downgrade('FILE_NULL_ON_GROUNDED');
  const abs = repoRoot ? path.join(repoRoot, rec.file) : rec.file;
  let src;
  try { src = fs.readFileSync(abs, 'utf8'); }
  catch (_) {
    // second chance: maybe rec.file was already absolute
    try { src = fs.readFileSync(rec.file, 'utf8'); }
    catch (__) { return downgrade('FILE_NOT_FOUND'); }
  }
  const srcLines = src.split(NL);
  const range = parseLines(rec.lines);
  if (!range) return downgrade('LINES_UNPARSEABLE');
  if (range[0] < 1 || range[1] > srcLines.length) return downgrade('LINES_OUT_OF_RANGE');

  // Gather the cited window (+/- context) and check each evidence quote against it.
  const from = Math.max(1, range[0] - CTX), to = Math.min(srcLines.length, range[1] + CTX);
  const windowText = loose(srcLines.slice(from - 1, to).join(' '));
  const evList = Array.isArray(rec.evidence) ? rec.evidence : (rec.evidence ? [rec.evidence] : []);
  if (evList.length === 0) return downgrade('EVIDENCE_EMPTY');

  const quotes = evList.map(quoteFromEvidence).filter((q) => q.length >= 3);
  const anyFound = quotes.some((q) => windowText.indexOf(loose(q)) !== -1);
  if (!anyFound) return downgrade('EVIDENCE_QUOTE_MISMATCH');

  // Verified. REPRODUCED keeps STRONG only if reproduction actually ran+reproduced.
  const repro = rec.reproduction && rec.reproduction.status;
  if (rec.status === 'REPRODUCED' && repro !== 'REPRODUCED') {
    out.status = 'SUPPORTED';
    out.confidence.evidence_strength = 'MEDIUM';
    out._evidence_check = { checked: true, quote_found: true, note: 'quote OK but reproduction.status != REPRODUCED -> SUPPORTED' };
    return out;
  }
  out._evidence_check = { checked: true, quote_found: true, matched_lines: `${from}-${to}`, note: 'verified' };
  return out;
}

function run(records, repoRoot) {
  const arr = Array.isArray(records) ? records : [];
  return arr.map((r) => checkOne(r || {}, repoRoot));
}

function selftest() {
  let n = 0, fails = 0;
  const t = (name, cond) => { n++; if (!cond) { console.error('FAIL:', name); fails++; } else console.log('ok  :', name); };
  const os = require('os');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'prism-ve-'));
  const f = path.join(tmp, 'auth.py');
  fs.writeFileSync(f, ['def reset_password():', '    tok = lookup()', '    update(tok)', '    # token record remains active after successful update', '    return ok'].join('\n'));

  const base = { file: 'auth.py', lines: '3-4', symbol: 'reset_password', category: 'security', claim: 'Reset token can be reused', confidence: {}, reproduction: { status: 'NOT_RUN' } };

  let r = run([Object.assign({}, base, { status: 'SUPPORTED', evidence: ['auth.py:4 — token record remains active after successful update'] })], tmp);
  t('real quote -> stays SUPPORTED', r[0].status === 'SUPPORTED' && r[0]._evidence_check.quote_found);

  r = run([Object.assign({}, base, { status: 'SUPPORTED', evidence: ['auth.py:4 — token is wiped and blacklisted immediately'] })], tmp);
  t('fabricated quote -> downgraded', r[0].status === 'SUSPECTED' && r[0].missing === 'EVIDENCE_QUOTE_MISMATCH');

  r = run([Object.assign({}, base, { status: 'SUPPORTED', lines: '900-902', evidence: ['x — y'] })], tmp);
  t('lines out of range -> downgraded', r[0].status === 'SUSPECTED' && r[0].missing === 'LINES_OUT_OF_RANGE');

  r = run([Object.assign({}, base, { file: 'nope.py', status: 'SUPPORTED', evidence: ['a — b'] })], tmp);
  t('missing file -> downgraded', r[0].status === 'SUSPECTED' && r[0].missing === 'FILE_NOT_FOUND');

  r = run([Object.assign({}, base, { status: 'REPRODUCED', evidence: ['auth.py:4 — token record remains active after successful update'], reproduction: { status: 'NOT_RUN' } })], tmp);
  t('REPRODUCED w/o actual repro -> SUPPORTED', r[0].status === 'SUPPORTED');

  const a = run([Object.assign({}, base, { claim: 'boundary bug one' })], tmp)[0].fingerprint;
  const b = run([Object.assign({}, base, { claim: 'boundary bug two' })], tmp)[0].fingerprint;
  t('same symbol+category, different claim -> different fingerprint', a !== b);

  const c1 = run([Object.assign({}, base)], tmp)[0].fingerprint;
  const c2 = run([Object.assign({}, base)], tmp)[0].fingerprint;
  t('fingerprint stable across runs', c1 === c2 && c1.length === 12);

  r = run([{ status: 'SUSPECTED', file: null, category: 'security', claim: 'maybe', confidence: {} }], tmp);
  t('file:null -> unpinned flag, no crash', r[0].unpinned === true && r[0]._evidence_check.checked === false);

  let threw = false;
  try { run(undefined); run(null); run([null, 42]); } catch (_) { threw = true; }
  t('never throws on junk', !threw);

  try { fs.rmSync(tmp, { recursive: true, force: true }); } catch (_) {}
  console.log(fails ? `\n${fails}/${n} FAILED` : `\nALL PASS (${n}/${n})`);
  process.exit(fails ? 1 : 0);
}

const args = process.argv.slice(2);
if (args[0] === '--selftest') {
  selftest();
} else {
  const file = args[0];
  const repoRoot = args[1] || process.cwd();
  let text = '';
  try { text = file ? fs.readFileSync(file, 'utf8') : fs.readFileSync(0, 'utf8'); } catch (_) { text = ''; }
  let records = [];
  try { records = JSON.parse(text); } catch (_) { records = []; }
  process.stdout.write(JSON.stringify(run(records, repoRoot), null, 2));
}
