#!/usr/bin/env node
/*
 * Deterministic gate / check / rank for the prism idea pass (references/ideas.md).
 *
 * The idea pass asks models for alternatives. Models happily produce generic, ungrounded advice,
 * pad every lens, and a checker can "drop" an idea by asserting something exists without showing
 * it. Every rule that stops that is enforced here, in code, not by instructions:
 *
 *   gate   : richest PRISM-IDEAS v1 fence (ties -> LAST, so an echoed example cannot win), JSON
 *            shape / enums / lengths / placeholder values, max 3 format-valid ideas per lens (the
 *            rest OVER_CAP, in emission order), every ground checked: a finding ID must be
 *            SUPPORTED/REPRODUCED in checked.json, a `path:lines — quote` must really sit at those
 *            lines (verify-evidence.js's matcher) in a file under the repo root or a --context file,
 *            no credential files. No valid ground -> UNGROUNDED.
 *   check  : applies PRISM-IDEA-CHECK v1 verdicts. DROP "exists"/"conflicts" needs a quote that
 *            verifies, else WEAK. No verdict -> UNCHECKED (never silently KEEP).
 *   rank   : merges engines. cross_model only from explicit groups the caller passes (the LLM groups
 *            semantically; this script never guesses). Order depends on content only.
 *
 * Usage:
 *   node verify-ideas.js gate <proposer-out> <claude|codex> <repo-root> [--findings checked.json] [--context <file>]...
 *   node verify-ideas.js check <gated.json> <checker-out> <repo-root> [--also <checker-out>]... [--context <file>]...
 *   node verify-ideas.js rank <checked-ideas.json>... [--groups groups.json]
 *   node verify-ideas.js --selftest
 * Exit: 0 = result JSON on stdout (a failed engine is degraded:true, still 0); 2 = usage/input error.
 *
 * Never throws, never writes files except to stdout, no deps besides ./verify-evidence.js.
 * SINGLE-SOURCED: canonical = prism-all/verify-ideas.js; prism + prism-codex copies are generated by
 * skills/sync-review-parsers.sh. Edit ONLY the canonical, then sync.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const VE = require('./verify-evidence.js');

const IDEAS_BEGIN = '<<<PRISM-IDEAS v1>>>';
const CHECK_BEGIN = '<<<PRISM-IDEA-CHECK v1>>>';
const END = '<<<END>>>';
const ENGINES = ['claude', 'codex'];
const LENSES = ['class', 'route', 'subtract'];
const COSTS = ['S', 'M', 'L'];
const VERDICTS = ['KEEP', 'WEAK', 'DROP'];
const BASES = ['exists', 'conflicts', 'not-solving', 'other'];
const QUOTE_BASES = new Set(['exists', 'conflicts']);
const CAP_PER_LENS = 3;
const MAX_GROUNDS = 5;
const MAX_GROUND_LEN = 600;
const MAX_IDEA_LINES = 60;       // JSON objects read from one fence; more are counted as overflow
const MIN_QUOTE = 8;             // loose characters; shorter quotes match too easily
const MAX_SPAN = 40;             // a ground may cite at most this many lines
// Text fields an idea must carry, with their maximum length. lens/cost/grounds are checked apart.
const IDEA_TEXT = { title: 120, problem: 500, proposal: 1500, replaces: 300, cost_note: 300, effect: 500, risk: 500 };
const IDEA_FIELDS = ['lens', 'title', 'problem', 'grounds', 'proposal', 'replaces', 'cost', 'cost_note', 'effect', 'risk'];
const CHECK_FIELDS = ['key', 'verdict', 'basis', 'reason', 'quote', 'cost', 'cost_note'];
const GROUNDED = VE.GROUNDED;    // SUPPORTED, REPRODUCED

// zero-width / bidi / word-joiner / soft-hyphen / BOM -- fence-token comparison only
// Built from code points: these characters must never appear raw in this source (U+2028/2029 are
// line terminators inside a regex literal).
const ch = (c) => String.fromCharCode(c);
const ZW = new RegExp('[' + ch(0x200B) + '-' + ch(0x200F) + ch(0x202A) + '-' + ch(0x202E) +
  ch(0x2060) + '-' + ch(0x2064) + ch(0xFEFF) + ch(0x00AD) + ']', 'g');
const NL = new RegExp('\\r\\n|\\n|\\r|' + ch(0x2028) + '|' + ch(0x2029));
const tok = (s) => String(s).replace(ZW, '').trim();
const isPlaceholder = (s) => /^<[^<>]+>$/.test(String(s).trim());
// path:lines — quote   (em/en dash, or " - "); Windows drive paths survive the lazy path match.
const LOC_RE = new RegExp('^(.+?):(\\d+(?:\\s*-\\s*\\d+)?)(?:\\s*[' + ch(0x2014) + ch(0x2013) + ']\\s*|\\s+-\\s+)(.+)$');
const FINDING_RE = /^`?(PRISM-\d+)`?$/i;
// Same families codex-run.sh refuses to send (is_credential_file); a ground may not quote them.
const CREDENTIAL_RE = new RegExp('^(?:' + [
  '\\.env', '\\.env\\..+', '.+\\.env', '\\.envrc', 'dotenv',
  '.+\\.(?:pem|key|p12|pfx|ppk|keystore|jks|token|tfvars|tfstate)',
  'id_(?:rsa|dsa|ecdsa|ed25519)(?:\\..+)?',
  '\\.netrc', '\\.npmrc', '\\.pypirc', '\\.pgpass', '\\.git-credentials', 'credentials(?:\\..+)?',
  '\\.credentials\\.json', 'auth\\.json', 'kubeconfig',
  '.*secret.*\\.(?:json|ya?ml|env|ini|toml|txt)', '.*credential.*\\.(?:json|ya?ml|ini|toml|txt)',
].join('|') + ')$', 'i');
const NOT_CREDENTIAL_RE = /\.(?:example|sample|template|dist)$/i;

// ---------------------------------------------------------------- fences + JSON lines

function blocksOf(text, begin) {
  const blocks = [];
  let cur = null;
  for (const ln of String(text == null ? '' : text).split(NL)) {
    const t = tok(ln);
    if (t === begin) { cur = []; blocks.push(cur); continue; }
    if (t === END) { cur = null; continue; }
    if (cur) cur.push(ln);
  }
  return blocks;
}

// -> { objs: [object...], bad: n, overflow: n, empty: bool }
function jsonLines(lines) {
  const objs = [];
  let bad = 0, overflow = 0, nonEmpty = 0;
  for (const raw of lines) {
    const t = raw.trim();
    if (!t) continue;
    nonEmpty++;
    let o = null;
    if (t[0] === '{') { try { o = JSON.parse(t); } catch (_) { o = null; } }
    if (!o || typeof o !== 'object' || Array.isArray(o)) { bad++; continue; }
    if (objs.length >= MAX_IDEA_LINES) { overflow++; continue; }
    objs.push(o);
  }
  return { objs, bad, overflow, empty: nonEmpty === 0 };
}

function str(v) { return typeof v === 'string' ? v.trim() : null; }

// -> { ok, reason, idea }
function validateIdea(o) {
  const idea = {};
  const lens = str(o.lens);
  if (!lens || LENSES.indexOf(lens.toLowerCase()) === -1) return { ok: false, reason: 'BAD_LENS' };
  idea.lens = lens.toLowerCase();
  for (const f of Object.keys(IDEA_TEXT)) {
    const v = str(o[f]);
    if (!v) return { ok: false, reason: `MISSING_${f.toUpperCase()}` };
    if (v.length > IDEA_TEXT[f]) return { ok: false, reason: `TOO_LONG_${f.toUpperCase()}` };
    if (isPlaceholder(v)) return { ok: false, reason: `PLACEHOLDER_${f.toUpperCase()}` };
    idea[f] = v;
  }
  const cost = str(o.cost);
  if (!cost || COSTS.indexOf(cost.toUpperCase()) === -1) return { ok: false, reason: 'BAD_COST' };
  idea.cost = cost.toUpperCase();
  if (!Array.isArray(o.grounds) || o.grounds.length < 1 || o.grounds.length > MAX_GROUNDS) {
    return { ok: false, reason: 'BAD_GROUNDS' };
  }
  const grounds = [];
  for (const g of o.grounds) {
    const s = str(g);
    if (!s || s.length > MAX_GROUND_LEN || isPlaceholder(s)) return { ok: false, reason: 'BAD_GROUNDS' };
    grounds.push(s);
  }
  idea.grounds = grounds;
  idea.additive = /^none\b/i.test(idea.replaces);
  return { ok: true, idea };
}

// ---------------------------------------------------------------- grounds

function samePath(a, b) {
  return process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b;
}
function inside(root, p) {
  const rel = path.relative(root, p);
  return rel !== '' && rel !== '..' && !rel.startsWith('..' + path.sep) && !path.isAbsolute(rel);
}
function realOr(p) { try { return fs.realpathSync(p); } catch (_) { return null; } }

// env: { root, rootReal, contexts: [{arg, abs, real, base}], findings: Map|null }
function resolveGroundPath(p, env) {
  const ctxHit = (c) => ({ ok: true, real: c.real, context: c.arg });
  for (const c of env.contexts) if (c.arg === p) return ctxHit(c);
  const byBase = env.contexts.filter((c) => c.base === p);
  if (byBase.length === 1) return ctxHit(byBase[0]);
  const abs = path.isAbsolute(p) ? path.resolve(p) : path.resolve(env.root, p);
  const real = realOr(abs);
  if (!real) return { ok: false, reason: inside(env.root, abs) ? 'FILE_NOT_FOUND' : 'PATH_OUTSIDE_ROOT' };
  for (const c of env.contexts) if (samePath(c.real, real)) return ctxHit(c);
  if (!env.rootReal || !inside(env.rootReal, real)) return { ok: false, reason: 'PATH_OUTSIDE_ROOT' };
  return { ok: true, real };
}

function isCredential(p) {
  const b = path.basename(String(p));
  return !NOT_CREDENTIAL_RE.test(b) && CREDENTIAL_RE.test(b);
}

function unwrapQuote(q) {
  const m = q.match(/^(["'`])([\s\S]*)\1$/);
  return (m ? m[2] : q).trim();
}

// `path:lines — quote` -> { ok, reason, file, lines, matched_lines }
function verifyQuote(raw, env) {
  const g = String(raw).trim().replace(/^`([^`]+)`/, '$1');
  const m = g.match(LOC_RE);
  if (!m) return { ok: false, reason: 'UNPARSEABLE_GROUND' };
  const p = m[1].trim().replace(/^`+|`+$/g, '');
  const quote = unwrapQuote(m[3].trim());
  const range = VE.parseLines(m[2]);
  if (!range) return { ok: false, reason: 'LINES_UNPARSEABLE' };
  if (range[1] - range[0] + 1 > MAX_SPAN) return { ok: false, reason: 'LINES_TOO_WIDE' };
  if (VE.loose(quote).length < MIN_QUOTE) return { ok: false, reason: 'QUOTE_TOO_SHORT' };
  const res = resolveGroundPath(p, env);
  if (!res.ok) return { ok: false, reason: res.reason };
  if (isCredential(p) || isCredential(res.real)) return { ok: false, reason: 'CREDENTIAL_FILE' };
  let src;
  try { src = fs.readFileSync(res.real, 'utf8'); } catch (_) { return { ok: false, reason: 'FILE_NOT_FOUND' }; }
  const srcLines = src.split(VE.NL);
  if (range[0] < 1 || range[1] > srcLines.length) return { ok: false, reason: 'LINES_OUT_OF_RANGE' };
  const w = VE.quoteWindow(srcLines, range);
  if (!VE.quoteInWindow(w.text, quote)) return { ok: false, reason: 'QUOTE_MISMATCH' };
  const out = { ok: true, file: p, lines: `${range[0]}-${range[1]}`, matched_lines: `${w.from}-${w.to}` };
  if (res.context) out.context = res.context;
  return out;
}

function checkGround(raw, env) {
  const fid = String(raw).trim().match(FINDING_RE);
  if (fid) {
    const id = fid[1].toUpperCase();
    const base = { ground: raw, kind: 'finding', finding: id };
    if (!env.findings) return Object.assign(base, { ok: false, reason: 'NO_FINDINGS_FILE' });
    const rec = env.findings.get(id);
    if (!rec) return Object.assign(base, { ok: false, reason: 'FINDING_NOT_FOUND' });
    if (!GROUNDED.has(rec.status)) return Object.assign(base, { ok: false, reason: `FINDING_NOT_GROUNDED:${rec.status}` });
    return Object.assign(base, { ok: true, strength: rec.status === 'REPRODUCED' ? 'REPRODUCED' : 'SUPPORTED' });
  }
  const q = verifyQuote(raw, env);
  const out = Object.assign({ ground: raw, kind: 'quote' }, q);
  if (q.ok) out.strength = 'QUOTE';
  return out;
}

const STRENGTH = { REPRODUCED: 0, SUPPORTED: 1, QUOTE: 2, NONE: 3 };
function bestStrength(list) {
  let best = 'NONE';
  for (const s of list) if (s && STRENGTH[s] < STRENGTH[best]) best = s;
  return best;
}

function makeEnv(repoRoot, findings, contextArgs) {
  const root = path.resolve(String(repoRoot || '.'));
  const contexts = [];
  for (const arg of contextArgs || []) {
    const abs = path.resolve(arg);
    const real = realOr(abs);
    if (real) contexts.push({ arg, abs, real, base: path.basename(arg) });
  }
  let fmap = null;
  if (findings) {
    fmap = new Map();
    const arr = Array.isArray(findings) ? findings : (findings && Array.isArray(findings.findings) ? findings.findings : []);
    for (const r of arr) {
      if (r && typeof r.id === 'string' && !fmap.has(r.id.toUpperCase())) fmap.set(r.id.toUpperCase(), r);
    }
  }
  return { root, rootReal: realOr(root), contexts, findings: fmap };
}

// ---------------------------------------------------------------- gate

function gate(text, engine, env) {
  const blocks = blocksOf(text, IDEAS_BEGIN);
  const parsed = blocks.map((b) => {
    const j = jsonLines(b);
    const checked = j.objs.map((o) => ({ o, v: validateIdea(o) }));
    return { j, checked, valid: checked.filter((c) => c.v.ok).length };
  });
  let best = null;
  for (const p of parsed) if (!best || p.valid >= best.valid) best = p;   // richest; ties -> LAST

  const counts = { proposed: 0, valid: 0, gated: 0, ungrounded: 0, over_cap: 0, invalid: 0, bad_lines: 0, overflow: 0 };
  const result = { kind: 'prism-ideas-gate', version: 1, engine, degraded: false, clean: false, blocks: blocks.length, counts, ideas: [] };
  if (!best) { result.degraded = true; result.note = 'no PRISM-IDEAS v1 fence'; return result; }

  counts.bad_lines = best.j.bad;
  counts.overflow = best.j.overflow;
  counts.proposed = best.checked.length;
  if (best.valid === 0) {
    if (blocks.length && parsed[parsed.length - 1].j.empty) result.clean = true;
    else { result.degraded = true; result.note = 'fence(s) present but no valid PRISM-IDEAS v1 line'; }
  }

  const perLens = {};
  best.checked.forEach((c, i) => {
    const key = `${engine}-${i + 1}`;
    if (!c.v.ok) {
      counts.invalid++;
      const t = c.o && typeof c.o.title === 'string' ? c.o.title.slice(0, 120) : null;
      result.ideas.push({ key, engine, status: 'INVALID', reason: c.v.reason, title: t });
      return;
    }
    counts.valid++;
    const idea = Object.assign({ key, engine }, c.v.idea);
    perLens[idea.lens] = (perLens[idea.lens] || 0) + 1;
    if (perLens[idea.lens] > CAP_PER_LENS) {
      counts.over_cap++;
      result.ideas.push(Object.assign(idea, { status: 'OVER_CAP', reason: `more than ${CAP_PER_LENS} ideas for lens ${idea.lens}` }));
      return;
    }
    idea.ground_checks = idea.grounds.map((g) => checkGround(g, env));
    const okFindings = new Set(idea.ground_checks.filter((g) => g.ok && g.kind === 'finding').map((g) => g.finding));
    const valid = idea.ground_checks.filter((g) => g.ok);
    idea.ground_strength = bestStrength(valid.map((g) => g.strength));
    const cited = (idea.problem.match(/PRISM-\d+/gi) || []).map((s) => s.toUpperCase());
    const unverified = cited.filter((id) => !okFindings.has(id));
    if (!valid.length) {
      counts.ungrounded++;
      idea.status = 'UNGROUNDED';
      idea.reason = 'NO_VALID_GROUND: ' + idea.ground_checks.map((g) => g.reason).join(', ');
    } else if (unverified.length) {
      counts.ungrounded++;
      idea.status = 'UNGROUNDED';
      idea.reason = `PROBLEM_CITES_UNGROUNDED_FINDING: ${unverified.join(', ')}`;
    } else {
      counts.gated++;
      idea.status = 'GATED';
    }
    result.ideas.push(idea);
  });
  return result;
}

// ---------------------------------------------------------------- check

function validateVerdict(o) {
  const key = str(o.key);
  if (!key || key.length > 40) return { ok: false, reason: 'BAD_KEY' };   // unknown keys are dropped later
  const verdict = str(o.verdict);
  if (!verdict || VERDICTS.indexOf(verdict.toUpperCase()) === -1) return { ok: false, reason: 'BAD_VERDICT' };
  const reason = str(o.reason);
  if (!reason || reason.length > 500 || isPlaceholder(reason)) return { ok: false, reason: 'BAD_REASON' };
  const v = { key, verdict: verdict.toUpperCase(), reason };
  const basis = str(o.basis);
  if (basis && BASES.indexOf(basis.toLowerCase()) !== -1) v.basis = basis.toLowerCase();
  if (v.verdict === 'DROP' && !v.basis) return { ok: false, reason: 'DROP_WITHOUT_BASIS' };
  const quote = str(o.quote);
  if (quote && !isPlaceholder(quote) && quote.length <= MAX_GROUND_LEN) v.quote = quote;
  const cost = str(o.cost);
  if (cost && COSTS.indexOf(cost.toUpperCase()) !== -1) {
    v.cost = cost.toUpperCase();
    const note = str(o.cost_note);
    if (note && !isPlaceholder(note)) v.cost_note = note.slice(0, 300);
  }
  return { ok: true, v };
}

function check(gated, texts, env) {
  const out = JSON.parse(JSON.stringify(gated || {}));
  if (!Array.isArray(out.ideas)) return { error: 'gated input has no ideas array' };
  out.ideas = out.ideas.filter((i) => i && typeof i === 'object' && typeof i.key === 'string');
  const gatedKeys = new Set(out.ideas.filter((i) => i.status === 'GATED').map((i) => i.key));
  const verdicts = new Map();
  let fences = 0, bad = 0, unknown = 0, repeated = 0;
  for (const text of texts) {
    for (const b of blocksOf(text, CHECK_BEGIN)) {
      fences++;
      const j = jsonLines(b);
      bad += j.bad;
      for (const o of j.objs) {
        const r = validateVerdict(o);
        if (!r.ok) { bad++; continue; }
        if (!gatedKeys.has(r.v.key)) { unknown++; continue; }
        if (verdicts.has(r.v.key)) repeated++;
        verdicts.set(r.v.key, r.v);                               // last verdict wins
      }
    }
  }
  const c = { keep: 0, weak: 0, drop: 0, unchecked: 0 };
  for (const idea of out.ideas) {
    if (idea.status !== 'GATED') continue;
    const v = verdicts.get(idea.key);
    if (!v) { idea.verdict = 'UNCHECKED'; idea.check = { note: 'NO_VERDICT' }; c.unchecked++; continue; }
    const chk = { reason: v.reason };
    if (v.basis) chk.basis = v.basis;
    let verdict = v.verdict;
    if (v.quote) {
      const q = verifyQuote(v.quote, env);
      chk.quote = v.quote;
      chk.quote_ok = q.ok;
      if (!q.ok) chk.quote_reason = q.reason;
    }
    if (verdict === 'DROP' && QUOTE_BASES.has(v.basis) && !chk.quote_ok) {
      verdict = 'WEAK';
      chk.note = `DROP_QUOTE_UNVERIFIED: ${chk.quote ? chk.quote_reason : 'QUOTE_MISSING'}`;
    }
    if (v.cost) { idea.cost_checked = v.cost; if (v.cost_note) chk.cost_note = v.cost_note; }
    idea.verdict = verdict;
    idea.check = chk;
    c[verdict.toLowerCase()]++;
  }
  out.kind = 'prism-ideas-checked';
  out.check = Object.assign({ degraded: fences === 0 || (verdicts.size === 0 && gatedKeys.size > 0), fences, bad_lines: bad, unknown_keys: unknown, repeated_keys: repeated }, c);
  return out;
}

// ---------------------------------------------------------------- rank

const VERDICT_ORDER = { KEEP: 0, WEAK: 1, UNCHECKED: 2, DROP: 3 };
const COST_ORDER = { S: 0, M: 1, L: 2 };
const normTitle = (s) => String(s || '').toLowerCase().replace(/\s+/g, ' ').trim();
const cmpStr = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function readGroups(groups) {
  if (groups == null) return [];
  if (!Array.isArray(groups)) return null;
  return groups.map((g) => (Array.isArray(g) ? g : (g && Array.isArray(g.keys) ? g.keys : null)));
}

function rank(inputs, groupsRaw) {
  const all = new Map();
  const meta = { proposed: 0, grounded: 0, keep: 0, weak: 0, drop: 0, unchecked: 0, ungrounded: 0, over_cap: 0, invalid: 0, bad_lines: 0, merged_away: 0, engines: [], degraded_engines: [], check_degraded: [] };
  for (const inp of inputs) {
    if (!inp || !Array.isArray(inp.ideas)) return { error: 'input without an ideas array' };
    const k = inp.counts || {};
    meta.proposed += k.proposed || 0;
    meta.grounded += k.gated || 0;
    meta.ungrounded += k.ungrounded || 0;
    meta.over_cap += k.over_cap || 0;
    meta.invalid += k.invalid || 0;
    meta.bad_lines += k.bad_lines || 0;
    if (inp.engine && meta.engines.indexOf(inp.engine) === -1) meta.engines.push(inp.engine);
    if (inp.degraded && meta.degraded_engines.indexOf(inp.engine) === -1) meta.degraded_engines.push(inp.engine);
    if (inp.check && inp.check.degraded && meta.check_degraded.indexOf(inp.engine) === -1) meta.check_degraded.push(inp.engine);
    for (const idea of inp.ideas) {
      if (!idea || typeof idea.key !== 'string') return { error: 'idea without a key' };
      if (all.has(idea.key)) return { error: `duplicate idea key ${idea.key}` };
      all.set(idea.key, idea);
    }
  }
  meta.engines.sort(); meta.degraded_engines.sort(); meta.check_degraded.sort();

  const groups = readGroups(groupsRaw);
  if (groups === null || groups.some((g) => g === null)) return { error: 'groups must be an array of key arrays' };
  const grouped = new Map();
  groups.forEach((keys, gi) => {
    for (const key of keys) {
      if (!all.has(key)) { grouped.set('\u0000error', `unknown key in groups: ${key}`); return; }
      if (grouped.has(key)) { grouped.set('\u0000error', `key in two groups: ${key}`); return; }
      grouped.set(key, gi);
    }
  });
  if (grouped.has('\u0000error')) return { error: grouped.get('\u0000error') };

  const verdictOf = (i) => i.verdict || 'UNCHECKED';
  const memberCmp = (a, b) => VERDICT_ORDER[verdictOf(a)] - VERDICT_ORDER[verdictOf(b)] || cmpStr(a.engine, b.engine) || cmpStr(a.key, b.key);

  // Entries: one per group (its GATED members) and one per ungrouped GATED idea.
  const buckets = new Map();
  for (const idea of all.values()) {
    if (idea.status !== 'GATED') continue;
    const b = grouped.has(idea.key) ? `g${grouped.get(idea.key)}` : `i:${idea.key}`;
    if (!buckets.has(b)) buckets.set(b, []);
    buckets.get(b).push(idea);
  }
  const entries = [];
  for (const members of buckets.values()) {
    members.sort((a, b) => cmpStr(a.engine, b.engine) || cmpStr(a.key, b.key));
    const checked = members.filter((m) => verdictOf(m) !== 'UNCHECKED');
    let verdict = 'UNCHECKED';
    for (const m of checked) if (verdict === 'UNCHECKED' || VERDICT_ORDER[verdictOf(m)] > VERDICT_ORDER[verdict]) verdict = verdictOf(m);
    const rep = members.slice().sort(memberCmp).find((m) => verdictOf(m) === verdict) || members[0];
    const engines = [];
    for (const m of members) if (engines.indexOf(m.engine) === -1) engines.push(m.engine);
    const grounds = [];
    for (const m of members) for (const g of m.ground_checks || []) if (g.ok && grounds.indexOf(g.ground) === -1) grounds.push(g.ground);
    meta.merged_away += members.length - 1;
    entries.push({
      verdict,
      cross_model: engines.length >= 2,
      engines,
      lens: rep.lens,
      title: rep.title,
      problem: rep.problem,
      proposal: rep.proposal,
      replaces: rep.replaces,
      additive: !!rep.additive,
      cost: rep.cost_checked || rep.cost,
      cost_note: rep.cost_note,
      effect: rep.effect,
      risk: rep.risk,
      grounds,
      ground_strength: bestStrength(members.map((m) => m.ground_strength)),
      check: rep.check || null,
      key: rep.key,
      engine: rep.engine,
      members: members.map((m) => ({ key: m.key, engine: m.engine, verdict: verdictOf(m) })),
    });
  }

  const entryCmp = (a, b) =>
    VERDICT_ORDER[a.verdict] - VERDICT_ORDER[b.verdict] ||
    (a.cross_model === b.cross_model ? 0 : a.cross_model ? -1 : 1) ||
    (a.additive === b.additive ? 0 : a.additive ? 1 : -1) ||
    COST_ORDER[a.cost] - COST_ORDER[b.cost] ||
    STRENGTH[a.ground_strength] - STRENGTH[b.ground_strength] ||
    cmpStr(normTitle(a.title), normTitle(b.title)) ||
    cmpStr(a.engine, b.engine) ||
    cmpStr(a.key, b.key);
  entries.sort(entryCmp);

  const ideas = [], dropped = [];
  for (const e of entries) {
    meta[e.verdict.toLowerCase()]++;
    if (e.verdict === 'DROP') dropped.push(e);
    else ideas.push(Object.assign({ id: `IDEA-${ideas.length + 1}` }, e));
  }
  const excluded = [];
  for (const idea of all.values()) {
    if (idea.status === 'GATED') continue;
    excluded.push({ key: idea.key, engine: idea.engine, status: idea.status, reason: idea.reason || null, title: idea.title || null });
  }
  excluded.sort((a, b) => cmpStr(a.engine, b.engine) || cmpStr(a.key, b.key));
  return { kind: 'prism-ideas-rank', version: 1, meta, ideas, dropped, excluded };
}

