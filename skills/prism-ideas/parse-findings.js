#!/usr/bin/env node
/*
 * Tier 2 deterministic findings parser for prism-all / prism-codex.
 *
 * Turns a reviewer output file into validated structured JSON so synthesis
 * triages RECORDS, not raw prose. Code does extraction; the LLM does semantic
 * triage. Self-contained, no deps, never throws.
 *
 * Output (stdout): {"angle","degraded":bool,"clean":bool,"skipped":N,"overflow":N,
 *                   "blocks":N,"findings":[{severity,locus,text}]}
 *
 * Contract (mirrors SKILL.md "출력 파서 v1"):
 *  - Fence tokens matched LINE-ANCHORED (whole trimmed line === token), never a raw
 *    substring. Zero-width/format chars stripped ONLY for token comparison --
 *    finding CONTENT is preserved byte-for-byte.
 *  - Scan ALL fenced blocks, pick the RICHEST (most valid findings); ties -> first.
 *    Survives Codex's doubled output AND a model that emits an illustrative/example
 *    fence BEFORE its real answer (the old first-block-only rule dropped the real
 *    review in that case).
 *  - Finding line `SEV | LOCUS | TEXT`: SEV normalized from a bounded vocabulary
 *    (crit/critical, high/major, med/medium/moderate, low/minor/nit/info) to
 *    CRIT|HIGH|MED|LOW; LOCUS non-empty pipe-free; TEXT non-empty (pipes ok). A
 *    leading list/quote marker ("- ","* ","> ","1. ") -- marker THEN space -- is
 *    stripped. Anything else skipped + counted.
 *  - Empty fence, no garbage -> CLEAN. No fence / only garbage -> DEGRADED (one
 *    visible marker; never silent-drop, never fail the round).
 *
 * Usage: node parse-findings.js <file> <angle>   |   node parse-findings.js --selftest
 *
 * SINGLE-SOURCED: canonical = prism-all/parse-findings.js; prism-codex's copy is
 * generated by skills/sync-review-parsers.sh. Edit ONLY the canonical, then sync.
 * Created by: Minwoo Park
 */
'use strict';
const fs = require('fs');

const BEGIN = '<<<PRISM-FINDINGS v1>>>';
const END = '<<<END>>>';
const MAX_FINDINGS = 200;
// zero-width / bidi / word-joiner / soft-hyphen / BOM -- token comparison ONLY
const ZW = /[​-‏‪-‮⁠-⁤﻿­]/g;
const NL = /\r\n|\n|\r|\u2028|\u2029/;
const LIST_PREFIX = /^(?:[-*>•]\s+|\d+[.)]\s+)?/;   // real marker FOLLOWED BY space
const REC = /^([A-Za-z]+)\s*\|\s*([^|]+?)\s*\|\s*(\S.*)$/;
const SEV_MAP = {
  CRIT: 'CRIT', CRITICAL: 'CRIT', BLOCKER: 'CRIT',
  HIGH: 'HIGH', MAJOR: 'HIGH',
  MED: 'MED', MEDIUM: 'MED', MODERATE: 'MED', WARN: 'MED', WARNING: 'MED',
  LOW: 'LOW', MINOR: 'LOW', NIT: 'LOW', INFO: 'LOW', TRIVIAL: 'LOW',
};
const tok = (s) => s.replace(ZW, '').trim();   // fence-token comparison only

function parseBody(bodyLines) {
  const findings = [];
  let skipped = 0, overflow = 0;
  for (const raw of bodyLines) {
    const t = raw.trim();
    if (!t) continue;
    const m = t.replace(LIST_PREFIX, '').match(REC);
    if (!m) { skipped++; continue; }
    const sev = SEV_MAP[m[1].toUpperCase()];
    const locus = m[2].trim(), text = m[3].trim();
    if (!sev || !locus || !text) { skipped++; continue; }   // unknown sev / empty field
    if (findings.length >= MAX_FINDINGS) { overflow++; continue; }
    findings.push({ severity: sev, locus, text });
  }
  return { findings, skipped, overflow };
}

function parse(text, angle) {
  angle = angle || 'unknown';
  text = typeof text === 'string' ? text : String(text == null ? '' : text);
  const lines = text.split(NL);

  const blocks = [];
  let cur = null;
  for (const ln of lines) {
    const t = tok(ln);
    if (t === BEGIN) { cur = []; blocks.push(cur); continue; }
    if (t === END) { cur = null; continue; }
    if (cur) cur.push(ln);   // keep original line (no global mutation)
  }

  let best = { findings: [], skipped: 0, overflow: 0 };
  let anyGarbage = false;
  for (const b of blocks) {
    const p = parseBody(b);
    if (p.skipped > 0) anyGarbage = true;
    if (p.findings.length > best.findings.length) best = p;   // richest; ties -> first
  }

  if (best.findings.length === 0) {
    if (blocks.length > 0 && !anyGarbage) {
      return { angle, degraded: false, clean: true, skipped: 0, overflow: 0, blocks: blocks.length, findings: [] };
    }
    return {
      angle, degraded: true, clean: false, skipped: best.skipped, overflow: 0, blocks: blocks.length,
      findings: [{
        severity: 'MED', locus: angle,
        text: blocks.length
          ? 'ANGLE-DEGRADED: fence(s) present but no valid v1 records -> inspect raw or re-run'
          : 'ANGLE-DEGRADED: no v1 fence found -> inspect raw or re-run'
      }]
    };
  }
  return { angle, degraded: false, clean: false, skipped: best.skipped, overflow: best.overflow, blocks: blocks.length, findings: best.findings };
}

function selftest() {
  let n = 0, fails = 0;
  const t = (name, cond) => { n++; if (!cond) { console.error('FAIL:', name); fails++; } else console.log('ok  :', name); };
  const ZWS = '​';

  let r = parse('reasoning\n<<<PRISM-FINDINGS v1>>>\nHIGH | foo.py:3 | bug -> fix\nLOW | bar | nit -> tidy\n<<<END>>>', 'devil');
  t('happy: 2 findings', r.findings.length === 2 && !r.degraded && !r.clean);

  r = parse('<<<PRISM-FINDINGS v1>>>\nCRIT | a | x -> y\n<<<END>>>\ntokens used\n<<<PRISM-FINDINGS v1>>>\nCRIT | a | x -> y\n<<<END>>>', 'x');
  t('doubled identical: 1 finding', r.findings.length === 1 && r.blocks === 2);

  r = parse('Here is the format:\n<<<PRISM-FINDINGS v1>>>\nHIGH | example | placeholder -> x\n<<<END>>>\nNow my real review:\n<<<PRISM-FINDINGS v1>>>\nCRIT | real.py:9 | real bug 1 -> fix\nHIGH | real.py:20 | real bug 2 -> fix\n<<<END>>>', 'devil');
  t('idx0: picks richer (real) block, not the stub', r.findings.length === 2 && r.findings[0].locus === 'real.py:9');

  r = parse('<<<PRISM-FINDINGS v1>>>\ncritical | a | sqli -> param\nMedium | b | perf -> cache\nnit | c | typo -> fix\n<<<END>>>', 'x');
  t('idx1: critical->CRIT, medium->MED, nit->LOW (none dropped)', r.findings.length === 3 && r.findings[0].severity === 'CRIT' && r.findings[1].severity === 'MED' && r.findings[2].severity === 'LOW');

  r = parse('I will emit a <<<PRISM-FINDINGS v1>>> block.\n<<<PRISM-FINDINGS v1>>>\nHIGH | real | x -> y\n<<<END>>>', 'x');
  t('prose-quote ignored', r.findings.length === 1 && r.findings[0].locus === 'real');

  r = parse('<<<PRISM-FINDINGS v1>>>\nMED | p | mentions <<<END>>> inline -> ok\nLOW | q | survives -> ok\n<<<END>>>', 'x');
  t('END-in-text: both survive', r.findings.length === 2);

  r = parse('<<<PRISM-FINDINGS v1>>>\nHIGH | only one field\nHIGH | loc |\nMED | | empty locus\nHowever | x | prose not a severity\nHIGH | good | real -> fix\n<<<END>>>', 'x');
  t('malformed/unknown-sev skipped, valid kept', r.findings.length === 1 && r.skipped === 4);

  r = parse('<<<PRISM-FINDINGS v1>>>\n<<<END>>>', 'x');
  t('empty fence: clean not degraded', r.clean === true && !r.degraded);

  r = parse('prose only', 'x');
  t('no fence: degraded', r.degraded === true && /no v1 fence/.test(r.findings[0].text));

  r = parse('<<<PRISM-FINDINGS v1>>>\nHIGH | a' + ZWS + 'b | keep' + ZWS + 'zw -> fix\n<<<END>>>', 'x');
  t('content ZW preserved', r.findings.length === 1 && r.findings[0].locus.indexOf(ZWS) !== -1);

  r = parse('<<<PRISM-FINDINGS v1>>>\n**HIGH** | a | b -> c\n<<<END>>>', 'x');
  t('markdown-bold SEV not accepted (skipped -> degraded)', r.degraded === true && !r.clean);

  r = parse('<<<PRISM-FINDINGS v1>>>\nHIGH | a | use `x | y` -> fix\n<<<END>>>', 'x');
  t('pipe-in-text preserved', r.findings.length === 1 && /x \| y/.test(r.findings[0].text));

  let threw = false;
  try { parse(undefined); parse(null); parse(42); } catch (_) { threw = true; }
  t('never throws on non-string', !threw);

  console.log(fails ? `\n${fails}/${n} FAILED` : `\nALL PASS (${n}/${n})`);
  process.exit(fails ? 1 : 0);
}

const args = process.argv.slice(2);
if (args[0] === '--selftest') {
  selftest();
} else {
  const file = args[0];
  const angle = args[1] || 'unknown';
  let text = '';
  try { text = fs.readFileSync(file, 'utf8'); } catch (_) { text = ''; }
  process.stdout.write(JSON.stringify(parse(text, angle)));
}
