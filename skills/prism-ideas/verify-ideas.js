#!/usr/bin/env node
/*
 * Deterministic gate / check / rank for the prism idea pass (references/ideas.md).
 *
 * The idea pass asks models for alternatives. Models happily produce generic, ungrounded advice,
 * pad every lens, and a checker can "drop" an idea by asserting something exists without showing
 * it. Every rule that stops that is enforced here, in code, not by instructions:
 *
 *   gate   : the answer is the LAST closed PRISM-IDEAS v1 fence (a fence that only echoes the
 *            contract's placeholder example is skipped), so a draft or a planted fence earlier in
 *            the output never wins, even when the last fence is invalid; a truncated (unclosed)
 *            last fence is no answer at all. JSON shape / enums / lengths /
 *            placeholder values; text is flattened to one line (no control, line-break or bidi
 *            characters). Max 3 format-valid ideas per lens (the rest OVER_CAP, in emission
 *            order). Every ground is checked: a finding ID must be SUPPORTED/REPRODUCED in a
 *            machine-checked checked.json; a `path:lines — quote` must really sit at those lines
 *            (verify-evidence.js's matcher) of a file under the repo root or a --context file, never
 *            a credential file, VCS internals or a secret-shaped quote. No valid ground ->
 *            UNGROUNDED. The text of a failed ground is never kept. Keys are `<engine>-<n>-<hash>`,
 *            bound to the idea's content, so a verdict or group written for another gate run cannot
 *            land on a different idea.
 *   check  : one checker output per batch; the last closed PRISM-IDEA-CHECK v1 fence of each
 *            output counts, and an empty one answers nothing. A DROP needs a quote that verifies unless its basis is not-solving
 *            (else WEAK). No verdict -> UNCHECKED (never KEEP), and a rejected verdict says why. A
 *            batch without a usable fence is a failed batch: the result is partial or degraded,
 *            never silently clean. Two checkers that disagree on a key: the stricter verdict stands.
 *   rank   : merges engines. cross_model only from explicit groups the caller passes (the LLM
 *            groups semantically; this script never guesses). Order depends on content only.
 *   prompt : builds the proposer and checker prompts (the same bytes for both engines; codex-run.sh
 *            ideas / idea-check run this builder and only add the Sandbox Safety Preamble).
 *   render : the report's IDEAS section from rank's output.
 *
 * Usage:
 *   node verify-ideas.js gate <proposer-out> <claude|codex> <repo-root> [--findings checked.json] [--target <file>]... [--context <file>]...
 *   node verify-ideas.js check <gated.json> <checker-out> <repo-root> [--also <checker-out>]... [--target <file>]... [--context <file>]... [--findings f]
 *   node verify-ideas.js rank <checked-ideas.json>... [--groups groups.json]
 *   node verify-ideas.js prompt propose --root <repo-root> --target <file>... [--findings checked.json] [--context <file>]...
 *   node verify-ideas.js prompt check --gated <gated.json>... [--findings checked.json] [--batch N]
 *   node verify-ideas.js render <ideas.json>
 *   node verify-ideas.js --selftest
 * A --target outside the repo root (by its path as written) is a quotable ground like a --context
 * file; inside, it is a repo file. check accepts --findings and ignores it (one ARGS list per run).
 * Exit: 0 = result JSON on stdout (a failed engine is degraded:true, still 0); 2 = usage/input error
 *       (an unreadable input file, a findings file of the wrong shape, a gate/check output of the
 *       wrong kind, a missing ./verify-evidence.js).
 *
 * Never throws, never writes files except to stdout, no deps besides ./verify-evidence.js.
 * SINGLE-SOURCED: canonical = prism-all/verify-ideas.js; prism + prism-codex copies are generated by
 * skills/sync-review-parsers.sh. Edit ONLY the canonical, then sync.
 */
