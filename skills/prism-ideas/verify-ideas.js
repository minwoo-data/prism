// Characters built from code points: they must never appear raw in this source (U+2028/2029 are
// line terminators inside a regex literal).
const ch = (c) => String.fromCharCode(c);
// zero-width / bidi embeddings and isolates / word-joiner / soft-hyphen / BOM
const ZW = new RegExp('[' + ch(0x200B) + '-' + ch(0x200F) + ch(0x202A) + '-' + ch(0x202E) +
  ch(0x2060) + '-' + ch(0x2069) + ch(0xFEFF) + ch(0x00AD) + ']', 'g');
// C0/C1 controls (line breaks and tabs included) and the Unicode line/paragraph separators
const CTRL = new RegExp('[\\u0000-\\u001F\\u007F-\\u009F' + ch(0x2028) + ch(0x2029) + ']', 'g');
// Model output is split into lines on real line breaks only: U+2028/2029 may sit raw inside a JSON
// string, and a fence hidden behind them is not a fence.
const LINE = /\r\n|\n|\r/;
const tok = (s) => String(s).replace(ZW, '').trim();
const clean = (s) => String(s).replace(ZW, '').replace(CTRL, ' ').replace(/\s+/g, ' ').trim();
const isPlaceholder = (s) => /^<[^<>]+>$/.test(String(s).trim());
// path:lines — quote   (em/en dash, or " - "); a range may use a hyphen or an en dash. Windows
// drive paths survive the lazy path match.
const LOC_RE = new RegExp('^(.+?):(\\d+(?:\\s*[-' + ch(0x2013) + ']\\s*\\d+)?)(?:\\s*[' + ch(0x2014) + ch(0x2013) + ']\\s*|\\s+-\\s+)(.+)$');
const FINDING_RE = /^`?(PRISM-\d+)`?$/i;

// The globs codex-run.sh is_credential_file refuses (the selftest compares the two lists when
// codex-run.sh sits next to this file). Matched case-insensitively against a basename; `*` may
// match nothing, exactly as in the shell.
const CREDENTIAL_GLOBS = [
  '.env', '.env.*', '*.env', '.envrc', 'dotenv', '*.pem', '*.key', '*.p12', '*.pfx', '*.ppk', '*.keystore', '*.jks', '*.token', '*.tfvars', '*.tfstate',
  'id_rsa', 'id_rsa.*', 'id_dsa', 'id_dsa.*', 'id_ecdsa', 'id_ecdsa.*', 'id_ed25519', 'id_ed25519.*',
  '.netrc', '.npmrc', '.pypirc', '.pgpass', '.git-credentials', 'credentials', 'credentials.*', '.credentials.json', 'auth.json', 'kubeconfig',
  '*secret*.json', '*secret*.yaml', '*secret*.yml', '*secret*.env', '*secret*.ini', '*secret*.toml', '*secret*.txt',
  '*credential*.json', '*credential*.yaml', '*credential*.yml', '*credential*.ini', '*credential*.toml', '*credential*.txt',
];
const NOT_CREDENTIAL_GLOBS = ['*.example', '*.sample', '*.template', '*.dist'];
const globRe = (globs) => new RegExp('^(?:' + globs.map((g) => g.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*')).join('|') + ')$', 'i');
const CREDENTIAL_RE = globRe(CREDENTIAL_GLOBS);
const NOT_CREDENTIAL_RE = globRe(NOT_CREDENTIAL_GLOBS);

const URL_RE = /[A-Za-z][A-Za-z0-9+.-]*:\/\/[^/\s:@]+:[^/\s:@]{6,}@/g;
// KEY = "literal": the value must be a quoted literal. An unquoted value is code (an environment
// lookup, a call, a constant) and names a secret without holding one.
const KV_RE = /[A-Z0-9_]*(?:SECRET|PASSWORD|PASSWD|TOKEN|API_KEY|APIKEY|ACCESS_KEY|PRIVATE_KEY)[A-Z0-9_]*["']?\s*[:=]\s*["'][A-Za-z0-9_@#%^&*!.+/=~$-]{8,}/g;
const LOCAL_HOST = /^(?:localhost|127\.0\.0\.1|0\.0\.0\.0|\[::1\])$/i;
// Stock passwords of local development databases; with a local host they are not a secret.
const DEV_PASSWORD = /^(?:password|passwd|secret|postgres|root|admin|test|example|dev|local)$/i;
// Free text (an idea's fields, a checker's reason) can carry a .env line, where values are not
// quoted: there an unquoted value with a letter and a digit, not code (no `.`, `(`, `<`), counts.
const KV_TEXT_RE = /[A-Z0-9_]*(?:SECRET|PASSWORD|PASSWD|TOKEN|API_KEY|APIKEY|ACCESS_KEY|PRIVATE_KEY)[A-Z0-9_]*\s*[:=]\s*([A-Za-z0-9_@#%^&*!+/=~$-]{8,})(?![.(<A-Za-z0-9_])/g;
// The shapes codex-run.sh secret_patterns() quarantines, plus HTTP auth headers. A quote that looks
// like a secret is never a ground: it would be copied into the report and the other engine's prompt.
const SECRET_RES = [
  /sk-ant-[a-z]{3}[0-9]{2}-[A-Za-z0-9_-]{20,}/g, /sk-proj-[A-Za-z0-9_-]{30,}/g, /sk-[A-Za-z0-9]{40,}/g,
  /(?:sk|rk)_live_[A-Za-z0-9]{20,}/g, /AIzaSy[A-Za-z0-9_-]{30,}/g, /AKIA[0-9A-Z]{16}/g, /glpat-[A-Za-z0-9_-]{20,}/g,
  /gh[pousr]_[A-Za-z0-9]{20,}/g, /github_pat_[A-Za-z0-9_]{22,}/g, /xox[abpr]-[A-Za-z0-9-]{20,}/g,
  /eyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}/g,
  URL_RE, KV_RE,
  /-----BEGIN (?:RSA |EC |DSA |OPENSSH |ENCRYPTED |)?PRIVATE KEY-----/g,
  /authorization\s*[:=]\s*["']?(?:basic|bearer|token)\s+[A-Za-z0-9+/=._~-]{12,}/gi,
];
// Example values reviewers write; never real secrets (same list as codex-run.sh PLACEHOLDER).
const SECRET_PLACEHOLDER = /(your[-_ ]|changeme|change_me|example|placeholder|dummy|redacted|xxxx|[*]{4}|[.]{3})/i;

// ---------------------------------------------------------------- fences + JSON lines

// -> { blocks: [[line...]] (closed fences only), unclosed: n }
function blocksOf(text, begin) {
  const blocks = [];
  let cur = null, unclosed = 0;
  for (const ln of String(text == null ? '' : text).split(LINE)) {
    const t = tok(ln);
    if (t === begin) { if (cur) unclosed++; cur = []; continue; }
    if (t === END) { if (cur) blocks.push(cur); cur = null; continue; }
    if (cur) cur.push(ln);
  }
  if (cur) unclosed++;
  return { blocks, unclosed, trailingOpen: cur !== null };   // trailingOpen: the last fence was cut off
}

// -> { objs: [object...], bad: n, overflow: n, empty: bool }
function jsonLines(lines) {
  const objs = [];
  let bad = 0, overflow = 0, nonEmpty = 0;
  for (const raw of lines) {
    const t = raw.trim();
    if (!t) continue;
    nonEmpty++;
    let o = null;
    if (t[0] === '{') { try { o = JSON.parse(t); } catch (_) { o = null; } }
    if (!o || typeof o !== 'object' || Array.isArray(o)) { bad++; continue; }
    if (objs.length >= MAX_IDEA_LINES) { overflow++; continue; }
    objs.push(o);
  }
  return { objs, bad, overflow, empty: nonEmpty === 0 };
}

// The answer is the last closed fence. Only an echoed contract example is skipped: a fence whose
// every line is JSON whose identifying field still holds the template placeholder (`lens` for an
// idea, `key` or `verdict` for a verdict). A draft or planted fence earlier in the output never
// wins, even when the last fence turns out invalid. -> index or -1
const echoOf = (fields) => (line) => {
  let o = null;
  try { o = JSON.parse(line); } catch (_) {
    // An abbreviated copy of the example (`{"lens":"<class|route|subtract>", ...}`) is not JSON.
    return fields.some((f) => new RegExp('"' + f + '"\\s*:\\s*"<[^"<>]+>"').test(line));
  }
  return !!o && typeof o === 'object' && fields.some((f) => typeof o[f] === 'string' && isPlaceholder(o[f]));
};
const IDEA_ECHO = echoOf(['lens']);
const CHECK_ECHO = echoOf(['key', 'verdict']);
function answerIndex(blocks, isEcho) {
  for (let i = blocks.length - 1; i >= 0; i--) {
    const lines = blocks[i].map((l) => l.trim()).filter(Boolean);
    if (lines.length && lines.every(isEcho)) continue;
    return i;
  }
  return -1;
}

function str(v) { return typeof v === 'string' ? clean(v) : null; }
const hash4 = (s) => crypto.createHash('sha1').update(s).digest('hex').slice(0, 4);

// -> { ok, reason, idea }
function validateIdea(o) {
  const idea = {};
  const lens = str(o.lens);
  if (!lens || LENSES.indexOf(lens.toLowerCase()) === -1) return { ok: false, reason: 'BAD_LENS' };
  idea.lens = lens.toLowerCase();
  for (const f of Object.keys(IDEA_TEXT)) {
    const v = str(o[f]);
    if (!v) return { ok: false, reason: `MISSING_${f.toUpperCase()}` };
    if (v.length > IDEA_TEXT[f]) return { ok: false, reason: `TOO_LONG_${f.toUpperCase()}` };
    if (isPlaceholder(v)) return { ok: false, reason: `PLACEHOLDER_${f.toUpperCase()}` };
    if (looksSecretText(v)) return { ok: false, reason: `SECRET_IN_${f.toUpperCase()}` };
    idea[f] = v;
  }
  const cost = str(o.cost);
  if (!cost || COSTS.indexOf(cost.toUpperCase()) === -1) return { ok: false, reason: 'BAD_COST' };
  idea.cost = cost.toUpperCase();
  if (!Array.isArray(o.grounds) || o.grounds.length < 1 || o.grounds.length > MAX_GROUNDS) {
    return { ok: false, reason: 'BAD_GROUNDS' };
  }
  const grounds = [];
  for (const g of o.grounds) {
    const s = str(g);
    if (!s || s.length > MAX_GROUND_LEN || isPlaceholder(s)) return { ok: false, reason: 'BAD_GROUNDS' };
    grounds.push(s);
  }
  idea.grounds = grounds;
  // The contract says to write exactly `none`; "N/A" and "nothing" mean the same.
  idea.additive = /^(?:none|nothing|n\/a)[.!]?$/i.test(idea.replaces);
  return { ok: true, idea };
}

// ---------------------------------------------------------------- grounds

// native resolves 8.3 short names and drops stream suffixes. It fails on some virtual volumes where
// the JS version works: then the JS result is used, unless it still holds a short-name component.
// (An object so the selftest can count calls.)
const FS_REAL = { native: fs.realpathSync.native || null, js: fs.realpathSync };
const SHORT_NAME = /^[^.~]{1,6}~\d+(?:\.[^.]{0,3})?$/i;   // an 8.3 short name such as ENV~1 or PROGRA~1
function samePath(a, b) {
  return process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b;
}
function inside(root, p) {
  const rel = path.relative(root, p);
  return rel !== '' && rel !== '..' && !rel.startsWith('..' + path.sep) && !path.isAbsolute(rel);
}
// Containment as written, no filesystem call: under the root or under its resolved form.
function underRoot(root, rootReal, abs) { return inside(root, abs) || !!(rootReal && inside(rootReal, abs)); }
function realOr(p) {
  if (FS_REAL.native) { try { return FS_REAL.native(p); } catch (_) { /* fall through */ } }
  try {
    const r = FS_REAL.js(p);
    return FS_REAL.native && process.platform === 'win32' && r.split(/[\\/]/).some((seg) => SHORT_NAME.test(seg)) ? null : r;
  } catch (_) { return null; }
}

// Shapes refused before any filesystem call: UNC and device paths (\\host\share, //host/share,
// \\?\, \\.\) would make the machine contact another host; a colon after the drive letter is an
// NTFS stream name or a URL.
function badPathShape(p) {
  if (/^[\\/]{2}/.test(p)) return 'UNC_PATH';
  if (p.replace(/^[A-Za-z]:/, '').indexOf(':') !== -1) return 'BAD_PATH';
  return null;
}

// Every file a ground's path can mean: a --context file named exactly as given or by the same
// absolute path, and the repo file. A quote is matched against each, so neither a repo file nor a
// context file can shadow the other. A --context basename counts only when nothing else matched.
// -> { ok: true, cands: [{ real, context? }] } | { ok: false, reason }
// env: { root, rootReal, contexts: [{arg, abs, real, base}], findings: Map|null }
function resolveGroundPath(p, env) {
  const shape = badPathShape(p);
  if (shape) return { ok: false, reason: shape };
  const cands = [];
  const add = (real, context) => { if (!cands.some((c) => samePath(c.real, real))) cands.push(context ? { real, context } : { real }); };
  for (const c of env.contexts) if (c.arg === p) add(c.real, c.arg);
  const abs = path.isAbsolute(p) ? path.resolve(p) : path.resolve(env.root, p);
  for (const c of env.contexts) if (samePath(c.abs, abs)) add(c.real, c.arg);
  let reason = 'PATH_OUTSIDE_ROOT';
  // Containment before touching the filesystem: a path outside the root is never opened.
  if (inside(env.root, abs) || (env.rootReal && inside(env.rootReal, abs))) {
    const real = realOr(abs);
    const ctx = real && env.contexts.find((c) => samePath(c.real, real));
    if (!real) reason = 'FILE_NOT_FOUND';
    else if (ctx) add(real, ctx.arg);
    else if (!env.rootReal || !inside(env.rootReal, real)) reason = 'PATH_OUTSIDE_ROOT';
    else if (path.relative(env.rootReal, real).split(path.sep).some((seg) => VCS_DIRS.has(seg.toLowerCase()))) reason = 'VCS_INTERNAL';
    else add(real, null);
  }
  if (!cands.length) {
    const byBase = env.contexts.filter((c) => c.base === p);
    if (byBase.length === 1) add(byBase[0].real, byBase[0].arg);
  }
  return cands.length ? { ok: true, cands } : { ok: false, reason };
}

function isCredential(p) {
  const b = path.basename(String(p));
  return !NOT_CREDENTIAL_RE.test(b) && CREDENTIAL_RE.test(b);
}

// True when a text holds something secret-shaped: a known token format, credentials in a URL, or a
// secret-named key with a quoted literal value. Code that only names a secret is not a secret, and
// neither is a local test DSN whose user and password are the same word.
function looksSecret(s) {
  for (const re of SECRET_RES) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(s)) !== null) {
      if (m[0].length === 0) { re.lastIndex++; continue; }
      if (SECRET_PLACEHOLDER.test(m[0])) continue;
      if (re === URL_RE) {
        const host = (s.slice(re.lastIndex).match(/^[^/:\s?#]*/) || [''])[0];
        const up = m[0].match(/:\/\/([^/\s:@]+):([^/\s:@]+)@$/);
        if (LOCAL_HOST.test(host) && up && (up[1] === up[2] || DEV_PASSWORD.test(up[2]))) continue;
      }
      return true;
    }
  }
  return false;
}

// looksSecret, plus unquoted KEY=value secrets: for free text, never for quotes of code.
function looksSecretText(s) {
  if (looksSecret(s)) return true;
  KV_TEXT_RE.lastIndex = 0;
  let m;
  while ((m = KV_TEXT_RE.exec(s)) !== null) {
    const v = m[1];
    if (/[A-Za-z]/.test(v) && /\d/.test(v) && !SECRET_PLACEHOLDER.test(v)) return true;
  }
  return false;
}

function unwrapQuote(q) {
  const m = q.match(/^(["'`])([\s\S]*)\1$/);
  return (m ? m[2] : q).trim();
}

// `path:lines — quote` -> { ok, reason, ref, file, lines, matched_lines, context? }
// `ref` is `path:lines` only: a failed quote's text is never carried forward.
function verifyQuote(raw, env) {
  const g = String(raw).trim().replace(/^`([^`]+)`/, '$1');
  const m = g.match(LOC_RE);
  if (!m) return { ok: false, reason: 'UNPARSEABLE_GROUND', ref: null };
  const p = m[1].trim().replace(/^`+|`+$/g, '');
  const linesTxt = m[2].replace(/\s+/g, '').replace(new RegExp(ch(0x2013), 'g'), '-');
  const ref = `${p}:${linesTxt}`;
  const fail = (reason) => ({ ok: false, reason, ref });
  // Cheapest and most specific first; nothing here touches the filesystem until resolveGroundPath.
  const shape = badPathShape(p);
  if (shape) return fail(shape);
  if (isCredential(p)) return fail('CREDENTIAL_FILE');
  const quote = unwrapQuote(m[3].trim());
  const range = VE.parseLines(linesTxt);
  if (!range) return fail('LINES_UNPARSEABLE');
  if (range[1] - range[0] + 1 > MAX_SPAN) return fail('LINES_TOO_WIDE');
  if (VE.loose(quote).length < MIN_QUOTE) return fail('QUOTE_TOO_SHORT');
  if (looksSecret(quote)) return fail('SECRET_IN_QUOTE');
  const res = resolveGroundPath(p, env);
  if (!res.ok) return fail(res.reason);
  let first = null, repoWhy = null;
  for (const c of res.cands) {
    const why = (() => {
      if (isCredential(c.real)) return 'CREDENTIAL_FILE';
      // A context or data file is quoted as values, so an unquoted KEY: value counts there. Code
      // keeps the quoted-only rule: it names secrets far more often than it holds them.
      if ((c.context || DATA_FILE.test(path.basename(c.real))) && looksSecretText(quote)) return 'SECRET_IN_QUOTE';
      let src;
      try { src = fs.readFileSync(c.real, 'utf8'); } catch (_) { return 'FILE_NOT_FOUND'; }
      const srcLines = src.split(VE.NL);
      if (range[0] < 1 || range[1] > srcLines.length) return 'LINES_OUT_OF_RANGE';
      const w = VE.quoteWindow(srcLines, range);
      // Quotes lose zero-width characters when cleaned, so the source window loses them too.
      if (!VE.quoteInWindow(w.text.replace(ZW, ''), quote)) return 'QUOTE_MISMATCH';
      return { from: w.from, to: w.to };
    })();
    if (typeof why === 'string') {
      if (why === 'CREDENTIAL_FILE' || why === 'SECRET_IN_QUOTE') return fail(why);   // never fall through past either
      if (!c.context) repoWhy = why; else first = first || why;
      continue;
    }
    const out = { ok: true, ref, file: p, lines: `${range[0]}-${range[1]}`, matched_lines: `${why.from}-${why.to}` };
    if (c.context) out.context = c.context;
    return out;
  }
  return fail(repoWhy || first || 'QUOTE_MISMATCH');   // the repo file's reason, when there is one
}

// Parentheses, not brackets: the report's inert escaping would show brackets as \[...\].
const withheld = (ref, reason) => (ref ? `${ref} — (quote withheld: ${reason})` : `(ground withheld: ${reason})`);

function checkGround(raw, env) {
  const fid = String(raw).trim().match(FINDING_RE);
  if (fid) {
    const id = fid[1].toUpperCase();
    const base = { ground: id, kind: 'finding', finding: id };
    const no = (reason) => Object.assign(base, { ok: false, reason });
    if (!env.findings) return no('NO_FINDINGS_FILE');
    const rec = env.findings.get(id);
    if (!rec) return no('FINDING_NOT_FOUND');
    if (rec.status === '\u0000DUPLICATE') return no('FINDING_ID_DUPLICATED');
    if (!GROUNDED.has(rec.status)) return no(`FINDING_NOT_GROUNDED:${rec.status}`);
    // Only a record verify-evidence.js actually quote-checked counts (records.json before the
    // machine check carries model-written statuses).
    const ec = rec._evidence_check;
    if (!ec || ec.checked !== true || ec.quote_found !== true) return no('FINDING_NOT_MACHINE_CHECKED');
    return Object.assign(base, { ok: true, strength: rec.status === 'REPRODUCED' ? 'REPRODUCED' : 'SUPPORTED' });
  }
  const q = verifyQuote(raw, env);
  if (!q.ok) return { ground: withheld(q.ref, q.reason), kind: 'quote', ok: false, reason: q.reason, ref: q.ref };
  return Object.assign({ ground: String(raw).trim(), kind: 'quote', strength: 'QUOTE' }, q);
}

const STRENGTH = { REPRODUCED: 0, SUPPORTED: 1, QUOTE: 2, NONE: 3 };
function bestStrength(list) {
  let best = 'NONE';
  for (const s of list) if (s && STRENGTH[s] < STRENGTH[best]) best = s;
  return best;
}

// -> { map, loaded, bad, duplicates } | { error }
function loadFindings(findings) {
  const arr = Array.isArray(findings) ? findings
    : (findings && typeof findings === 'object' && Array.isArray(findings.findings) ? findings.findings : null);
  if (!arr) return { error: 'the findings file must be the JSON array verify-evidence.js prints (or {"findings": [...]})' };
  const map = new Map(), dup = new Set();
  let bad = 0;
  for (const r of arr) {
    if (!r || typeof r.id !== 'string' || !r.id.trim()) { bad++; continue; }
    const id = r.id.trim().toUpperCase();
    if (map.has(id)) dup.add(id); else map.set(id, r);
  }
  for (const id of dup) map.set(id, { id, status: '\u0000DUPLICATE' });   // ambiguous: never a ground
  return { map, loaded: map.size - dup.size, bad, duplicates: dup.size };
}

function makeEnv(repoRoot, findings, contextArgs) {
  const root = path.resolve(String(repoRoot || '.'));
  const contexts = [];
  for (const arg of contextArgs || []) {
    if (typeof arg !== 'string' || badPathShape(arg)) continue;
    const abs = path.resolve(arg);
    const real = realOr(abs);
    if (real) contexts.push({ arg, abs, real, base: path.basename(arg) });
  }
  const env = { root, rootReal: realOr(root), contexts, findings: null, findingsInfo: null, findingsError: null };
  if (findings != null) {
    const f = loadFindings(findings);
    if (f.error) env.findingsError = f.error;
    else { env.findings = f.map; env.findingsInfo = { loaded: f.loaded, bad: f.bad, duplicates: f.duplicates }; }
  }
  return env;
}

// ---------------------------------------------------------------- gate

function gate(text, engine, env) {
  const { blocks, unclosed, trailingOpen } = blocksOf(text, IDEAS_BEGIN);
  const at = trailingOpen ? -1 : answerIndex(blocks, IDEA_ECHO);

  const counts = { proposed: 0, valid: 0, gated: 0, ungrounded: 0, over_cap: 0, invalid: 0, bad_lines: 0, overflow: 0, unclosed, ignored_fences: 0 };
  const result = { kind: 'prism-ideas-gate', version: 1, engine, root: env.rootReal || env.root, degraded: false, clean: false, blocks: blocks.length, counts, ideas: [] };
  if (env.findingsInfo) result.findings = env.findingsInfo;
  if (!env.rootReal) { result.degraded = true; result.note = `repo root cannot be resolved: ${env.root}`; }
  if (at === -1) {
    result.degraded = true;
    result.note = trailingOpen ? 'the last PRISM-IDEAS v1 fence never closed (no <<<END>>>): cut off, not an answer'
      : (blocks.length ? 'only echoed contract examples, no answer fence' : (unclosed ? 'PRISM-IDEAS v1 fence never closed (no <<<END>>>): not an answer' : 'no PRISM-IDEAS v1 fence'));
    const fb = String(text == null ? '' : text).match(/^\s*\[fallback: ([^\]\r\n]{1,80})\]/);
    if (fb) result.note += `; fallback: ${clean(fb[1])}`;
    return result;
  }
  const j = jsonLines(blocks[at]);
  const best = { j, checked: j.objs.map((o) => ({ o, v: validateIdea(o) })) };
  counts.ignored_fences = blocks.length - 1;
  counts.bad_lines = j.bad;
  counts.overflow = j.overflow;
  counts.proposed = best.checked.length;
  if (j.empty) result.clean = true;
  else if (!best.checked.some((c) => c.v.ok)) { result.degraded = true; result.note = 'the answer fence holds no valid PRISM-IDEAS v1 line'; }
  if (counts.ignored_fences && !result.note) result.note = `${counts.ignored_fences} other fence(s) ignored: only the last answer counts`;

  const perLens = {};
  best.checked.forEach((c, i) => {
    if (!c.v.ok) {
      counts.invalid++;
      const t = c.o && typeof c.o.title === 'string' ? clean(c.o.title).slice(0, 120) : null;
      result.ideas.push({ key: `${engine}-${i + 1}-${hash4(JSON.stringify(c.o))}`, engine, status: 'INVALID', reason: c.v.reason, title: t });
      return;
    }
    counts.valid++;
    const v = c.v.idea;
    const key = `${engine}-${i + 1}-${hash4([v.lens, v.title, v.proposal].join('\n'))}`;
    const idea = Object.assign({ key, engine }, v);
    perLens[idea.lens] = (perLens[idea.lens] || 0) + 1;
    if (perLens[idea.lens] > CAP_PER_LENS) {
      counts.over_cap++;
      idea.grounds = [];   // never checked, never carried
      result.ideas.push(Object.assign(idea, { status: 'OVER_CAP', reason: `more than ${CAP_PER_LENS} ideas for lens ${idea.lens}` }));
      return;
    }
    idea.ground_checks = v.grounds.map((g) => checkGround(g, env));
    const valid = idea.ground_checks.filter((g) => g.ok);
    idea.grounds = valid.map((g) => g.ground);            // a failed ground's text is not kept
    idea.grounds_failed = idea.ground_checks.length - valid.length;
    idea.ground_strength = bestStrength(valid.map((g) => g.strength));
    const okFindings = new Set(valid.filter((g) => g.kind === 'finding').map((g) => g.finding));
    const cited = (idea.problem.match(/PRISM-\d+/gi) || []).map((s) => s.toUpperCase());
    const unverified = cited.filter((id) => !okFindings.has(id));
    if (!valid.length) {
      counts.ungrounded++;
      idea.status = 'UNGROUNDED';
      idea.reason = 'NO_VALID_GROUND: ' + idea.ground_checks.map((g) => g.reason).join(', ');
    } else if (unverified.length) {
      counts.ungrounded++;
      idea.status = 'UNGROUNDED';
      idea.reason = `PROBLEM_CITES_UNGROUNDED_FINDING: ${unverified.join(', ')}`;
    } else {
      counts.gated++;
      idea.status = 'GATED';
    }
    result.ideas.push(idea);
  });
  return result;
}

// ---------------------------------------------------------------- check

// -> { ok: true, v } | { ok: false, reason, key }
function validateVerdict(o) {
  const key = str(o.key);
  const no = (reason) => ({ ok: false, reason, key });
  if (!key || key.length > 40) return no('BAD_KEY');   // unknown keys are dropped later
  const verdict = str(o.verdict);
  if (!verdict || VERDICTS.indexOf(verdict.toUpperCase()) === -1) return no('BAD_VERDICT');
  const reason = str(o.reason);
  if (!reason || reason.length > MAX_REASON || isPlaceholder(reason)) return no('BAD_REASON');
  if (looksSecretText(reason)) return no('SECRET_IN_REASON');
  const v = { key, verdict: verdict.toUpperCase(), reason };
  const basis = str(o.basis);
  if (basis && BASES.indexOf(basis.toLowerCase()) !== -1) v.basis = basis.toLowerCase();
  if (v.verdict === 'DROP' && !v.basis) return no('DROP_WITHOUT_BASIS');
  const quote = str(o.quote);
  if (quote) {
    if (isPlaceholder(quote)) v.quote_bad = 'PLACEHOLDER';
    else if (quote.length > MAX_GROUND_LEN) v.quote_bad = 'QUOTE_TOO_LONG';
    else v.quote = quote;
  }
  const cost = str(o.cost);
  if (cost && COSTS.indexOf(cost.toUpperCase()) !== -1) {
    v.cost = cost.toUpperCase();
    const note = str(o.cost_note);
    // The note is shown in the report like the reason, so it gets the same secret check.
    if (note && !isPlaceholder(note)) v.cost_note = looksSecretText(note) ? '(cost note withheld: secret-shaped)' : note.slice(0, 300);
  }
  return { ok: true, v };
}

const VERDICT_ORDER = { KEEP: 0, WEAK: 1, UNCHECKED: 2, DROP: 3 };
const STRICT = { KEEP: 0, WEAK: 1, DROP: 2 };   // between two checkers' answers, the stricter stands

// One checker answer -> { verdict, chk, cost }. A DROP stands only on a quote that verifies, unless
// its basis is not-solving (a judgment the grounds themselves show).
function judge(v, env) {
  const chk = { reason: v.reason };
  if (v.basis) chk.basis = v.basis;
  let verdict = v.verdict;
  if (v.quote_bad) { chk.quote_ok = false; chk.quote_reason = v.quote_bad; }
  else if (v.quote) {
    const q = verifyQuote(v.quote, env);
    chk.quote_ok = q.ok;
    if (q.ok) chk.quote = v.quote;
    else { chk.quote_ref = q.ref; chk.quote_reason = q.reason; }   // a failed quote's text is not kept
  }
  if (verdict === 'DROP' && v.basis !== NO_QUOTE_BASIS && !chk.quote_ok) {
    verdict = 'WEAK';
    chk.note = `DROP_QUOTE_UNVERIFIED: ${chk.quote_reason || 'QUOTE_MISSING'}`;
  }
  if (v.cost && v.cost_note) chk.cost_note = v.cost_note;
  return { verdict, chk, cost: v.cost || null };
}

// texts: one checker output per batch (the --also files are further batches).
function check(gated, texts, env) {
  if (!gated || gated.kind !== 'prism-ideas-gate' || !Array.isArray(gated.ideas)) {
    return { error: 'check takes the JSON that gate prints (kind prism-ideas-gate); re-check from gated.json, never from a checked file' };
  }
  if (gated.root && env.rootReal && !samePath(gated.root, env.rootReal)) {
    return { error: `repo root ${env.rootReal} differs from the gate run's ${gated.root}` };
  }
  const out = JSON.parse(JSON.stringify(gated));
  out.ideas = out.ideas.filter((i) => i && typeof i === 'object' && typeof i.key === 'string');
  const gatedKeys = new Set(out.ideas.filter((i) => i.status === 'GATED').map((i) => i.key));
  const answers = new Map();    // key -> [verdict object, one per batch that answered it]
  const rejected = new Map();   // key -> reason of the last rejected verdict line for it
  const batches = [];
  let bad = 0, rejectedLines = 0, unknown = 0, repeated = 0;
  (texts || []).forEach((text, bi) => {
    const { blocks, unclosed, trailingOpen } = blocksOf(text, CHECK_BEGIN);
    const at = trailingOpen ? -1 : answerIndex(blocks, CHECK_ECHO);
    const info = { batch: bi + 1, answered: 0, fences: blocks.length, unclosed, fallback: /^\s*\[fallback:/.test(String(text || '')) };
    if (at === -1) { info.failed = true; info.why = trailingOpen ? 'cut-off fence' : (blocks.length ? 'only echoed examples' : 'no fence'); batches.push(info); return; }
    const j = jsonLines(blocks[at]);
    // An empty checker answer answers nothing: the batch failed.
    if (j.empty) { info.failed = true; info.why = 'empty fence'; batches.push(info); return; }
    const chosen = { j, rs: j.objs.map(validateVerdict) };
    bad += chosen.j.bad;
    const mine = new Map();
    for (const r of chosen.rs) {
      if (!r.ok) {
        rejectedLines++;
        if (r.key && gatedKeys.has(r.key)) rejected.set(r.key, r.reason);
        continue;
      }
      if (!gatedKeys.has(r.v.key)) { unknown++; continue; }
      if (mine.has(r.v.key)) repeated++;
      mine.set(r.v.key, r.v);                                   // within one output, the last line wins
    }
    for (const [k, v] of mine) { if (!answers.has(k)) answers.set(k, []); answers.get(k).push(v); }
    info.answered = mine.size;
    if (!mine.size) { info.failed = true; info.why = 'no valid verdict'; }
    batches.push(info);
  });

  const c = { keep: 0, weak: 0, drop: 0, unchecked: 0 };
  let conflicts = 0;
  for (const idea of out.ideas) {
    delete idea.verdict; delete idea.check; delete idea.cost_checked;
    if (idea.status !== 'GATED') continue;
    const list = answers.get(idea.key);
    if (!list) {
      idea.verdict = 'UNCHECKED';
      idea.check = { note: rejected.has(idea.key) ? `VERDICT_REJECTED:${rejected.get(idea.key)}` : 'NO_VERDICT' };
      c.unchecked++;
      continue;
    }
    const judged = list.map((v) => judge(v, env));
    let pick = judged[0];
    for (const j of judged) if (STRICT[j.verdict] > STRICT[pick.verdict]) pick = j;
    if (judged.some((j) => j.verdict !== pick.verdict)) { conflicts++; pick.chk.note = (pick.chk.note ? pick.chk.note + '; ' : '') + 'CHECKERS_DISAGREE: the stricter verdict stands'; }
    if (pick.cost) idea.cost_checked = pick.cost;
    idea.verdict = pick.verdict;
    idea.check = pick.chk;
    c[pick.verdict.toLowerCase()]++;
  }
  const answered = [...gatedKeys].filter((k) => answers.has(k)).length;
  const failed = batches.filter((b) => b.failed).length;
  out.kind = 'prism-ideas-checked';
  out.check = Object.assign({
    degraded: gatedKeys.size > 0 && answered === 0,
    partial: answered > 0 && answered < gatedKeys.size,
    batches, failed_batches: failed, bad_lines: bad, rejected_lines: rejectedLines,
    unknown_keys: unknown, repeated_keys: repeated, conflicts,
  }, c);
  return out;
}

// ---------------------------------------------------------------- rank

const COST_ORDER = { S: 0, M: 1, L: 2 };
const normTitle = (s) => String(s || '').toLowerCase().replace(/\s+/g, ' ').trim();
const cmpStr = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function readGroups(groups) {
  if (groups == null) return [];
  if (!Array.isArray(groups)) return null;
  return groups.map((g) => (Array.isArray(g) ? g : (g && Array.isArray(g.keys) ? g.keys : null)));
}

function rank(inputs, groupsRaw) {
  const all = new Map();
  const meta = { proposed: 0, grounded: 0, keep: 0, weak: 0, drop: 0, unchecked: 0, ungrounded: 0, over_cap: 0, invalid: 0, bad_lines: 0, overflow: 0, unclosed: 0, merged_away: 0,
    engines: [], degraded_engines: [], degraded_notes: [], check_degraded: [], check_partial: [],
    check: { failed_batches: 0, bad_lines: 0, rejected_lines: 0, unknown_keys: 0, repeated_keys: 0, conflicts: 0 } };
  const addTo = (list, v) => { if (v && list.indexOf(v) === -1) list.push(v); };
  for (const inp of inputs) {
    if (!inp || !Array.isArray(inp.ideas)) return { error: 'input without an ideas array' };
    // A gate output is accepted only when it has nothing to check (a degraded or idea-less engine).
    if (inp.kind === 'prism-ideas-gate') {
      if (inp.ideas.some((i) => i && i.status === 'GATED')) return { error: `${inp.engine || 'an engine'}'s ideas were never checked: pass the output of check, not gate` };
    } else if (inp.kind !== 'prism-ideas-checked') {
      return { error: 'rank takes the JSON that check prints (kind prism-ideas-checked)' };
    }
    const k = inp.counts || {};
    for (const f of ['proposed', 'ungrounded', 'over_cap', 'invalid', 'bad_lines', 'overflow', 'unclosed']) meta[f] += k[f] || 0;
    meta.grounded += k.gated || 0;
    addTo(meta.engines, inp.engine);
    if (inp.degraded) addTo(meta.degraded_engines, inp.engine);
    // The gate's note says why (no fence, cut off, a fallback marker); the report shows it.
    if (inp.degraded && inp.note) meta.degraded_notes.push({ engine: inp.engine, note: String(inp.note).slice(0, 300) });
    if (inp.check) {
      if (inp.check.degraded) addTo(meta.check_degraded, inp.engine);
      if (inp.check.partial) addTo(meta.check_partial, inp.engine);
      for (const f of Object.keys(meta.check)) meta.check[f] += inp.check[f] || 0;
    }
    for (const idea of inp.ideas) {
      if (!idea || typeof idea.key !== 'string') return { error: 'idea without a key' };
      if (all.has(idea.key)) return { error: `duplicate idea key ${idea.key}` };
      all.set(idea.key, idea);
    }
  }
  for (const f of ['engines', 'degraded_engines', 'check_degraded', 'check_partial']) meta[f].sort();
  meta.degraded_notes.sort((a, b) => cmpStr(String(a.engine), String(b.engine)));

  const groups = readGroups(groupsRaw);
  if (groups === null || groups.some((g) => g === null)) return { error: 'groups must be an array of key arrays' };
  const grouped = new Map();
  for (let gi = 0; gi < groups.length; gi++) {
    for (const key of groups[gi]) {
      if (!all.has(key)) return { error: `unknown key in groups: ${key}` };
      if (grouped.has(key)) return { error: `key in two groups: ${key}` };
      grouped.set(key, gi);
    }
  }

  const verdictOf = (i) => i.verdict || 'UNCHECKED';
  const memberCmp = (a, b) => VERDICT_ORDER[verdictOf(a)] - VERDICT_ORDER[verdictOf(b)] || cmpStr(a.engine, b.engine) || cmpStr(a.key, b.key);

  // Entries: one per group (its GATED members) and one per ungrouped GATED idea.
  const buckets = new Map();
  for (const idea of all.values()) {
    if (idea.status !== 'GATED') continue;
    const b = grouped.has(idea.key) ? `g${grouped.get(idea.key)}` : `i:${idea.key}`;
    if (!buckets.has(b)) buckets.set(b, []);
    buckets.get(b).push(idea);
  }
  const entries = [];
  for (const members of buckets.values()) {
    members.sort((a, b) => cmpStr(a.engine, b.engine) || cmpStr(a.key, b.key));
    const checked = members.filter((m) => verdictOf(m) !== 'UNCHECKED');
    let verdict = 'UNCHECKED';
    for (const m of checked) if (verdict === 'UNCHECKED' || VERDICT_ORDER[verdictOf(m)] > VERDICT_ORDER[verdict]) verdict = verdictOf(m);
    const rep = members.slice().sort(memberCmp).find((m) => verdictOf(m) === verdict) || members[0];
    const engines = [];
    for (const m of members) if (engines.indexOf(m.engine) === -1) engines.push(m.engine);
    const grounds = [], groundsDetail = [], seenRefs = new Set();
    for (const m of members) for (const g of m.ground_checks || []) {
      const at = g.kind === 'quote' && g.ref ? `${g.context ? 'context:' : ''}${g.ref}` : g.ground;   // one ground per cited location
      if (g.ok && !seenRefs.has(at)) {
        seenRefs.add(at);
        grounds.push(g.ground);
        groundsDetail.push(Object.assign({ ground: g.ground, kind: g.kind, strength: g.strength }, g.context ? { context: g.context } : {}));
      }
    }
    meta.merged_away += members.length - 1;
    entries.push({
      verdict,
      cross_model: engines.length >= 2,
      engines,
      lens: rep.lens,
      title: rep.title,
      problem: rep.problem,
      proposal: rep.proposal,
      replaces: rep.replaces,
      additive: !!rep.additive,
      cost: rep.cost_checked || rep.cost,
      cost_note: rep.cost_note,
      effect: rep.effect,
      risk: rep.risk,
      grounds,
      grounds_detail: groundsDetail,
      grounds_failed: members.reduce((n, m) => n + (m.grounds_failed || 0), 0),
      ground_strength: bestStrength(members.map((m) => m.ground_strength)),
      check: rep.check || null,
      key: rep.key,
      engine: rep.engine,
      members: members.map((m) => ({ key: m.key, engine: m.engine, verdict: verdictOf(m) })),
    });
  }

  const entryCmp = (a, b) =>
    VERDICT_ORDER[a.verdict] - VERDICT_ORDER[b.verdict] ||
    (a.cross_model === b.cross_model ? 0 : a.cross_model ? -1 : 1) ||
    (a.additive === b.additive ? 0 : a.additive ? 1 : -1) ||
    COST_ORDER[a.cost] - COST_ORDER[b.cost] ||
    STRENGTH[a.ground_strength] - STRENGTH[b.ground_strength] ||
    cmpStr(normTitle(a.title), normTitle(b.title)) ||
    cmpStr(a.engine, b.engine) ||
    cmpStr(a.key, b.key);
  entries.sort(entryCmp);

  const ideas = [], dropped = [];
  for (const e of entries) {
    meta[e.verdict.toLowerCase()]++;
    if (e.verdict === 'DROP') dropped.push(e);
    else ideas.push(Object.assign({ id: `IDEA-${ideas.length + 1}` }, e));
  }
  const excluded = [];
  for (const idea of all.values()) {
    if (idea.status === 'GATED') continue;
    excluded.push({ key: idea.key, engine: idea.engine, status: idea.status, reason: idea.reason || null, title: idea.title || null });
  }
  excluded.sort((a, b) => cmpStr(a.engine, b.engine) || cmpStr(a.key, b.key));
  return { kind: 'prism-ideas-rank', version: 1, meta, ideas, dropped, excluded };
}

