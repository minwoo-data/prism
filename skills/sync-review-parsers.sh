#!/usr/bin/env bash
# Single-source the deterministic scripts AND the shared reference docs. Canonical = prism-all/*.
# prism-codex and prism receive generated copies.
#
#   bash skills/sync-review-parsers.sh           report drift, then write the copies
#   bash skills/sync-review-parsers.sh --check   report drift only; exit 1 if any copy differs
#
# parse-findings.js, verify-evidence.js, references/{record-v2,redteam-lens,design-lenses}.md are
# byte-identical across skills. references/codex-invocation.md (name-rewritten) and codex-run.sh
# (byte-identical; it derives its skill name from its directory) go to prism-codex only: prism is
# Claude-only. verify-independence.js differs per skill (SELF_NAME / REQUIRED_FILES /
# PREREQUISITES), so it is generated by a sed/perl rewrite of the canonical.
# Copies are built in a temp dir, compared with what is on disk, then moved into place.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
mode=sync; [ "${1:-}" = --check ] && mode=check
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

IDENTICAL=(parse-findings.js verify-evidence.js references/record-v2.md references/redteam-lens.md references/design-lenses.md)
expected=()   # "<dest relative to skills/>"; content lives at $tmp/<dest>

want() { mkdir -p "$(dirname "$tmp/$1")"; cat > "$tmp/$1"; expected+=("$1"); }

for f in "${IDENTICAL[@]}"; do
  want "prism-codex/$f" < "$here/prism-all/$f"
  want "prism/$f" < "$here/prism-all/$f"
done
# Input redirection, never `... | want`: a pipeline runs want in a subshell and loses expected+=.
want prism-codex/references/codex-invocation.md < <(sed 's/prism-all/prism-codex/g' "$here/prism-all/references/codex-invocation.md")
want prism-codex/codex-run.sh < "$here/prism-all/codex-run.sh"
want prism-codex/verify-independence.js < <(sed 's/prism-all/prism-codex/g' "$here/prism-all/verify-independence.js")
want prism/verify-independence.js < <(sed 's/prism-all/prism/g' "$here/prism-all/verify-independence.js" \
  | perl -0pe "s/const PREREQUISITES = \[\n  \{ cmd: 'codex --version', label: 'Codex CLI', fatal: true, min: '0\.125\.0' \},\n\];/const PREREQUISITES = []; \/\/ prism is Claude-only — no external CLI prerequisite/" \
  | perl -pe "s/, 'references\/codex-invocation.md'//; s/, 'codex-run.sh'//g")
[ ${#expected[@]} -eq 14 ] || { echo "sync FAILED: expected 14 generated copies, built ${#expected[@]}" >&2; exit 1; }
grep -q "const PREREQUISITES = \[\]" "$tmp/prism/verify-independence.js" || { echo "sync FAILED: prism PREREQUISITES rewrite did not apply" >&2; exit 1; }

drift=0
for rel in "${expected[@]}"; do
  if ! cmp -s "$tmp/$rel" "$here/$rel" 2>/dev/null; then
    echo "DRIFT: $rel differs from what prism-all generates" >&2; drift=1
  fi
done
for stale in prism/references/codex-invocation.md prism/codex-run.sh; do
  [ -e "$here/$stale" ] && { echo "DRIFT: $stale must not exist (prism is Claude-only)" >&2; drift=1; }
done

if [ "$mode" = check ]; then
  [ "$drift" = 0 ] && echo "in sync: ${#expected[@]} generated copies match prism-all" || exit 1
  exit 0
fi

for rel in "${expected[@]}"; do
  mv -f "$tmp/$rel" "$here/$rel.sync.$$" && mv -f "$here/$rel.sync.$$" "$here/$rel"
done
chmod +x "$here/prism-all/codex-run.sh" "$here/prism-codex/codex-run.sh"
rm -f "$here/prism/references/codex-invocation.md" "$here/prism/codex-run.sh"
echo "synced ${#expected[@]} copies -> prism-codex, prism$([ "$drift" = 0 ] && echo ' (no drift found)' || echo ' (drift above was overwritten)')"
